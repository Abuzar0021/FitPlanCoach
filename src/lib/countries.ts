export const COUNTRIES: Country[] = RAW.map(([code, name]) => ({
  code,
  name,
  flag: codeToFlag(code),
})).sort((a, b) => a.name.localeCompare(b.name));

const BY_NAME = new Map(COUNTRIES.map((c) => [c.name.toLowerCase(), c]));

/** Emoji flag for a stored country value (🌍 for global / unknown). */
export function flagFor(value?: string | null): string {
  if (!value || value.toLowerCase() === GLOBAL_COUNTRY) return "🌍";
  return BY_NAME.get(value.toLowerCase())?.flag ?? "🌍";
}

/** Display label for a stored country value. */
export function countryLabel(value?: string | null): string {
  if (!value || value.toLowerCase() === GLOBAL_COUNTRY) return "Global";
  return BY_NAME.get(value.toLowerCase())?.name ?? value;
}
