// Canonical country list for registration, profile, and food localization.
//
// The value stored on `profiles.country` is the country `name` (or the
// GLOBAL_COUNTRY sentinel for "Global / Other"). Meal generation matches it
// case-insensitively against `foods.country` and falls back to global meals
// when there's no local data, so every value here is always safe to store.

export const GLOBAL_COUNTRY = "global";

export interface Country {
  /** ISO 3166-1 alpha-2 code. */
  code: string;
  name: string;
  /** Emoji flag, derived from `code`. */
  flag: string;
}

/** Turn an ISO alpha-2 code into its regional-indicator emoji flag. */
function codeToFlag(code: string): string {
  return code
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65));
}

